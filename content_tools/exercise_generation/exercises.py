def spokencard_one_type(exercise_type,n_exercises = 10, topic = 'Business'):
    """
    pre: You are asked to fill in the type of exercise you want to create and n_exercises is the number of vocabulary items generated by OpenAI.
    post: creates a list of dictionaries where the keys are 'target_content' and the values of these keys are elements
    that fit the required type and format
    Comment: the reason why this function does not immediately create a JSON file is to be able to generate random subtypes using the spokencard() function cf. below
    -> to create a JSON file with the same content as this function, see spokencard_jsonfile(exercise_type,n_exercises = 10, topic = 'Business')
    Example: [{"target_content": "I am looking for a *full-time* position."}, {"target_content": "Who are your main *suppliers*?"}, {"target_content": "Thank you for considering my *application*."}, {"target_content": "He has poor *communication* skills."}, {"target_content": "Good leaders focus on tasks and *people*."}, {"target_content": "*Managers* sell products online."}, {"target_content": "Recruiters use LinkedIn to find *employees*."}, {"target_content": "Let's have dinner to *discuss* our new hire."}, {"target_content": "* Policies* change the way we sell products."}, {"target_content": "I am the chairman of the *board*."}]
    """
    # Creating a panda Dataframe to retrieve all of the example data
    df= pd.read_csv("content_tools/content_examples_csvs/spokencard.csv")
    
    # creating the complements needed for certain types of prompts
    vc1_complement = ", which contains either the phoneme /ɪ/ or /i:/,"
    vc2_complement = ", which contains either the phoneme /ɔː/ or /əʊ/,"
    ed_complement = ", which ends in '-ed',"
    if exercise_type in ['WS-SW','VC1-SW']:
        ws_sw = aux.filter_data(df['WS single word'].to_string())
        vc1_sw = aux.filter_data(df['VC1 single word'].to_string())
        prompt_type = {'WS-SW': [ws_sw,""],'VC1-SW': [vc1_sw,vc1_complement]}
        prompt = "Here is a list of words" + prompt_type[exercise_type][1] + " from a Business English vocabulary list.\n" + prompt_type[exercise_type][0] + "\nGenerate " + str(n_exercises) + " more words that could be found in a " + topic + " English vocabulary list."
        response=aux.generate_response(prompt, frequency_penalty=0.4,presence_penalty = 0.4)
        text = response.choices[0]['text']
        l = text.split('\n')
        del l[0:2] # the first 2 elements are "\n"
        l = aux.remove_numbering(l)
        if exercise_type == 'VC1-SW':
            filtered_list = []
            for element in l:
                if element in cmudict_dict:
                    for phon in cmudict_dict[element][0]:
                        if re.search('IH|IY[012]',phon):
                            filtered_list.append(element)
                            break # if we don't break, the same word could be twice in the list if you have two phonemes that fit the requirements
            l = filtered_list
    elif exercise_type in ['WS-WG','WS-S','VC1-WG','VC1-S','VC2-WG','VC2-S','-ED-WG','-ED-S']:
        ws_wg = aux.filter_data(df['WS word group'].to_string())
        ws_s = aux.filter_data(df['WS sentence'].to_string())
        vc1_wg = aux.filter_data(df['VC1 word group'].to_string())
        vc1_s = aux.filter_data(df['VC1 sentence'].to_string())
        vc2_wg = aux.filter_data(df['VC2 word group'].to_string())
        vc2_s = aux.filter_data(df['VC2 sentence'].to_string())
        ed_wg = aux.filter_data(df['-ED word group'].to_string())
        ed_s = aux.filter_data(df['-ED sentence'].to_string())
        # dictionary to adapt the prompt depending on type of exercise (WS-WG, WS-S, VC1-WG, VC1-S, VC2-WG, VC2-S). 
        prompt_type = {'WS-WG':['word groups',ws_wg,""],'WS-S':['sentences',ws_s,""],'VC1-WG':['word groups',vc1_wg,vc1_complement],'VC1-S':['sentences',vc1_s,vc1_complement],'VC2-WG':['word groups',vc2_wg,vc2_complement],'VC2-S':['sentences',vc2_s,vc2_complement],'-ED-WG':['word groups',ed_wg,ed_complement],'-ED-S':['sentences',ed_s,ed_complement]}
        prompt = "Here is a list of " + prompt_type[exercise_type][0] + " where emphasis on one word in particular" + prompt_type[exercise_type][2] + " is indicated using asterisks (*), from a Business English vocabulary list.\n" + prompt_type[exercise_type][1] + "\nGenerate " + str(n_exercises) + " more " + prompt_type[exercise_type][0] + " where emphasis on one word in particular"  + prompt_type[exercise_type][2] + " is indicated using asterisks (*) and that could be found in a " + topic + " English vocabulary list."
        response=aux.generate_response(prompt, frequency_penalty=0.4,presence_penalty = 0.4)
        text = response.choices[0]['text']
        l = text.split('\n')
        del l[0:2] # the first 2 elements are "\n"
        l = aux.remove_numbering(l)
        if exercise_type in ['VC1-WG','VC1-S','VC2-WG','VC2-S','-ED-WG','-ED-S']: #we have to check wheter the emphasized word indeed contains one of the required phonemes
            filtered_list = []
            for element in l:
                x = re.search('\*.+\*',element) # the word inbetween asterisks has to be isolated
                if x: # only proceeds if asterisks were found
                    y = x.group()
                    y = re.sub("\*", "", y) # asterisks need to be removed to check if entry is in cmudict
                    if exercise_type == '-ED-WG' or exercise_type == '-ED-S': # for these exercise types, the requirements are visible on word level, no need to go to the phonetic level
                        if re.search('ed$',y):
                            filtered_list.append(element)
                    elif y in cmudict_dict:
                        for phon in cmudict_dict[y][0]:
                            if exercise_type == 'VC1-WG' or exercise_type == 'VC1-S':
                                if re.search('IH|IY[012]',phon):
                                    filtered_list.append(element)
                                    break
                            elif exercise_type == 'VC2-WG' or exercise_type == 'VC2-S':
                                if re.search('AO|OW[012]',phon):
                                    filtered_list.append(element)
                                    break
            l = filtered_list                    
    final_list = []
    for word_group in l:
        d = {}
        d['target_content'] = word_group
        final_list.append(d)
    return final_list
    
