"""
3) Exercise type : Match Audio to Stress Pattern
Comment: It is important to ask OpenAI to generate long lists of vocabulary, or else the end result will generate almost no exercices because it won't have
enough content to work with. Also, the program currently takes a lot of time to run. Function match_word_to_stress_pattern works much better and reliably in my opinion

"""
def match_audio_to_stress_pattern(n_exercises = 10, topic = "Business"):
    """
    pre: n_exercises is the number of vocabulary items generated by OpenAI, topic is the topic about which OpenAI will generate vocabulary items
    post: creates a JSON file with a list of dictionaries where the 3 keys are 'target_content','incorrect1' and 'incorrect2'
        and the values are the vocabulary items related to these keys. Number of syllables for each dictionary value must be the same but
        the stress pattern of the 'target_content' key must be different to those of the 'incorrect' keys.
    Example: [{"target_content": "pediatrics", "incorrect1": "cholesterol", "incorrect2": "macrophages"}]
    """
    prompt = "Give me a list of "+ str(n_exercises)+" relating to the topic of " + topic + ", in random order"
    response=aux.generate_response(prompt, frequency_penalty=0.4,presence_penalty = 0.4)
    text = response.choices[0]['text']
    liste = aux.filter(text)
    d = aux.syllable_sort(liste)
    final_list = []
    for i in range(20): # tries to generates 20 exercises
        l = []
        key = random.choice(list(d)) # access a random amount of syllables
        for j in range(3):
            item = random.choice(d[key]) # access a random value containing a random amount of syllables
            l.append(item)
        for item in l:
            dico = {}
            if aux.stress_pattern(l[0]) != aux.stress_pattern(l[1]) and aux.stress_pattern(l[0]) != aux.stress_pattern(l[2]) and l[1] != l[2]:
                dico['target_content'] = l[0]
                dico['incorrect1'] = l[1]
                dico['incorrect2'] = l[2]
                final_list.append(dico)
    aux.jsonfile(final_list)

